package pl.offline.supaplex;

import android.app.*;
import android.os.Bundle;
import android.content.Intent;
import android.net.Uri;
import android.provider.DocumentsContract;
import android.database.Cursor;
import android.widget.*;
import java.io.*;

/** First-run data picker. SDL is not started until the user's data validates. */
public class ImportActivity extends Activity {
    private TextView status;
    private boolean busy;
    private boolean pl;
    private String tr(String en,String polish) {return pl?polish:en;}
    @Override public void onCreate(Bundle state) {
        super.onCreate(state);
        pl=getSharedPreferences("touch-controls",MODE_PRIVATE).getString("language",java.util.Locale.getDefault().getLanguage()).equals("pl");
        if(GameData.ready(getFilesDir())) {prepareAudioAndLaunch();return;}
        LinearLayout body=new LinearLayout(this);body.setOrientation(LinearLayout.VERTICAL);body.setPadding(32,16,32,16);
        ScrollView scroll=new ScrollView(this);scroll.addView(body);setContentView(scroll);
        TextView title=new TextView(this);title.setTextSize(22);title.setText(tr("Add your PC/DOS game files","Dodaj własne pliki gry PC/DOS"));body.addView(title);
        status=new TextView(this);status.setText(tr("This port does not include Supaplex game data. Select a folder or ZIP from your own legally obtained PC/DOS copy. The Google Play app is not a compatible data source. Existing saves and controls are kept. New procedural sound effects are generated by this port. Compatible user-supplied WAV/XM audio is optional.","Ten port nie zawiera danych gry Supaplex. Wybierz folder lub ZIP z własnej legalnie uzyskanej kopii PC/DOS. Aplikacja z Google Play nie jest zgodnym źródłem danych. Zapisy i ustawienia zostają zachowane. Port generuje własne efekty dźwiękowe. Własne zgodne pliki WAV/XM są opcjonalne."));body.addView(status);
        button(body,tr("Choose folder","Wybierz folder"),()->pick(true));
        button(body,tr("Choose ZIP","Wybierz ZIP"),()->pick(false));
        button(body,"Polski / English",()->{getSharedPreferences("touch-controls",MODE_PRIVATE).edit().putString("language",pl?"en":"pl").apply();recreate();});
    }
    private void button(LinearLayout body,String text,Runnable action) {Button b=new Button(this);b.setAllCaps(false);b.setText(text);body.addView(b);b.setOnClickListener(v->{if(!busy)action.run();});}
    private void pick(boolean tree) {
        Intent intent=new Intent(tree?Intent.ACTION_OPEN_DOCUMENT_TREE:Intent.ACTION_OPEN_DOCUMENT);
        if(!tree) {intent.setType("*/*");intent.addCategory(Intent.CATEGORY_OPENABLE);}
        try {startActivityForResult(intent,tree?1:2);}catch(android.content.ActivityNotFoundException e){status.setText(tr("No system file picker available.","Brak systemowego wyboru plików."));}
    }
    private void prepareAudioAndLaunch() {
        new Thread(()->{
            try {GeneratedAudio.ensure(getFilesDir());}catch(IOException e) {android.util.Log.w("Supaplex","Generated audio unavailable");}
            runOnUiThread(()->{if(!isFinishing() && !isDestroyed())launch();});
        },"generated-audio").start();
    }
    private void launch() {startActivity(new Intent(this,GameActivity.class));finish();}
    private int count;
    private long bytes;
    private void folder(Uri tree,String id,File stage,int depth,String path) throws IOException {
        if(depth>8)throw new IOException("Folder nesting too deep");
        Uri children=DocumentsContract.buildChildDocumentsUriUsingTree(tree,id);
        try(Cursor cursor=getContentResolver().query(children,new String[]{DocumentsContract.Document.COLUMN_DOCUMENT_ID,DocumentsContract.Document.COLUMN_DISPLAY_NAME,DocumentsContract.Document.COLUMN_MIME_TYPE},null,null,null)) {
            if(cursor==null)throw new IOException("Cannot read folder");
            while(cursor.moveToNext()) {
                if(++count>4096)throw new IOException("Too many files");
                String child=cursor.getString(0),name=cursor.getString(1),mime=cursor.getString(2);
                if(DocumentsContract.Document.MIME_TYPE_DIR.equals(mime))folder(tree,child,stage,depth+1,path+"/"+name);
                else {
                    String target=GameData.target(path+"/"+name);
                    if(target!=null)try(InputStream in=getContentResolver().openInputStream(DocumentsContract.buildDocumentUriUsingTree(tree,child))) {
                        if(in==null)throw new IOException("Cannot open file");GameData.copy(in,stage,target);bytes+=new File(stage,target).length();if(bytes>32*1024*1024)throw new IOException("Folder too large");
                    }
                }
            }
        }
    }
    @Override protected void onActivityResult(int request,int result,Intent data) {
        super.onActivityResult(request,result,data);
        if(result!=RESULT_OK || data==null || data.getData()==null)return;
        Uri uri=data.getData();busy=true;status.setText(tr("Checking and importing…","Sprawdzanie i importowanie…"));
        new Thread(()->{
            File stage=new File(getCacheDir(),"game-import");String error=null;
            try {
                GameData.clear(stage);if(!stage.mkdirs())throw new IOException("Cannot prepare import");count=0;bytes=0;
                if(request==1)folder(uri,DocumentsContract.getTreeDocumentId(uri),stage,0,"");
                else {InputStream in=getContentResolver().openInputStream(uri);if(in==null)throw new IOException("Cannot open ZIP");GameData.zip(in,stage);}
                GameData.install(stage,getFilesDir());
            }catch(Exception e){error=e.getMessage();}
            finally {try{GameData.clear(stage);}catch(IOException ignored){}}
            final String failure=error;runOnUiThread(()->{busy=false;if(isFinishing() || isDestroyed())return;if(failure==null)prepareAudioAndLaunch();else status.setText(tr("Import failed. Choose a complete PC/DOS game folder or ZIP. ","Import nieudany. Wybierz kompletny folder lub ZIP gry PC/DOS. ")+failure);});
        },"game-import").start();
    }
}
